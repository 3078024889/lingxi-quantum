export async function POST(req: Request) {
  const key = process.env.ZHIPU_API_KEY;
  if (!key) {
    return NextResponse.json({ error: "尚未配置灵犀解析（缺少 ZHIPU_API_KEY）。" }, { status: 503 });
  }

  // v225：限流——这个接口没有登录门槛，同一个 IP 每 60 秒最多 12 次。
  // 一个真实用户正常使用（写一次梦境、问一次问题、刷一次今日邀请）
  // 远远用不到这个上限，但能挡住脚本短时间内密集刷这个接口、把免费
  // 档位本就有限的并发占满。
  const ip = getClientIp(req);
  const allowed = await checkRateLimit(`lingxi:${ip}`, 12, 60);
  if (!allowed) {
    return NextResponse.json(
      { error: "请求太频繁了，请稍等一分钟再试。" },
      { status: 429 }
    );
  }

  let body: { mode?: string; content?: string; context?: string; mood?: string; lang?: string };
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "请求格式有误。" }, { status: 400 });
  }

  const mode = body.mode === "manifest" || body.mode === "invite" || body.mode === "ask" || body.mode === "lifemap" ? body.mode : "dream";
  const content = (body.content || "").trim();
  if (!content) return NextResponse.json({ error: "内容为空。" }, { status: 400 });
  const lang = body.lang === "en" ? "en" : "zh";
  const mood = (body.mood || "").trim();

  // invite 依语言选择系统提示
  const systemKey = mode === "invite" && lang === "en" ? "invite_en" : mode;

  const userText =
    mode === "dream"
      ? `【梦境】\n${content}\n${body.context ? `【联想与感受】\n${body.context}` : ""}`
      : mode === "invite"
        ? `${lang === "en" ? "[Gate]" : "【门】"} ${content}\n` +
          `${lang === "en" ? "[Today's state]" : "【今日状态】"} ${mood || (lang === "en" ? "(not provided)" : "（未填写）")}\n` +
          `${body.context ? `${lang === "en" ? "[Recent records]" : "【用户近期记录（梦境/签到摘录）】"}\n${body.context}` : ""}`
        : mode === "ask"
          ? `【提问】\n${content}`
          : mode === "lifemap"
            ? `${content}\n${body.context ? `【补充信息】\n${body.context}` : ""}`
            : `【我正在显化的生活】\n${content}\n${body.context ? `【此刻的感受】\n${body.context}` : ""}`;

  // ask 和 lifemap 模式，没有单独的英文版提示词，用附加指令的方式让模型直接输出英文，
  // 避免维护两份几乎重复、容易互相走样的中英提示词。
  // 全局规则：不管哪个模式，都不能在回答里出现"AI"这两个字母（也不能说
  // "人工智能""机器人"这类同义词）——灵犀的定位是"场"，不是"AI产品"，
  // 这条比其余任何一条格式规则都更靠前，统一加在这里，不用每个模式的
  // 提示词里分别写一遍、容易漏改。
  const noAiRule = "\n\n【最高优先级规则】回答全文，任何情况下都不能出现\"AI\"这两个字母，也不能用\"人工智能\"\"机器人\"\"聊天机器人\"\"程序\"这类词替代——灵犀是「场」，不是「AI产品」，这条规则优先于其余任何一条格式要求。";

  const langAppend =
    (lang === "en" && (mode === "ask" || mode === "lifemap")
      ? "\n\n【IMPORTANT】Write your ENTIRE response in natural, fluent English instead of Chinese — not a literal translation, written as if originally composed in English, same tone and format as specified above."
      : "") + noAiRule;

  try {
    // v225：这个接口只服务免费高频功能（签到、解梦、提问、生命图谱预览），
    // 付费的完整报告各自有独立、带登录+付费校验的 /api/*/generate-full
    // 接口。之前这里还留着一个 "lifemap-full" 分支，用 8000 token 生成
    // 付费级别的完整内容，但这个接口本身没有登录校验、没有付费校验、
    // 也没有限流——等于任何人只要知道这个参数，就能绕开付费墙免费生成，
    // 而且前端从没真的调用过这个分支（真正的付费生成走的是
    // /api/lifemap/generate-full）。这次直接删掉这个分支，不再留着这个
    // 口子。
    const maxTokens = 1200;
    const callOnce = () =>
      fetch(ENDPOINT, {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model: MODEL,
          temperature: 0.9,
          max_tokens: maxTokens,
          frequency_penalty: 0.4,
          presence_penalty: 0.3,
          messages: [
            { role: "system", content: SYSTEM[systemKey] + langAppend },
            { role: "user", content: userText },
          ],
          // 知识库检索：回答前先从灵犀知识库取相关 Codex 片段
          tools: [
            {
              type: "retrieval",
              retrieval: { knowledge_id: KNOWLEDGE_ID, prompt_template: PROMPT_TEMPLATE },
            },
          ],
        }),
      });

    let res = await callOnce();
    // 429（限流）大概率是短时间内请求太密集，不是真的坏了——等1.2秒
    // 再试一次，很大概率就通过了，不用把这种"缓一下就好"的情况，直接
    // 丢给用户去手动点"稍后再试"。只重试一次，避免真的出问题时卡住
    // 用户太久。
    if (res.status === 429) {
      await new Promise((r) => setTimeout(r, 1200));
      res = await callOnce();
    }

    if (!res.ok) {
      return NextResponse.json({ error: `场域暂时无法回应（${res.status}），请稍后再试。` }, { status: 500 });
    }
    const data = await res.json();
    const text: string | undefined = data?.choices?.[0]?.message?.content;
    if (!text) return NextResponse.json({ error: "场域沉默了，请稍后再试。" }, { status: 500 });

    if (mode === "invite") {
      try {
        const cleaned = text.replace(/```json|```/g, "").trim();
        const arr = JSON.parse(cleaned);
        const invites = Array.isArray(arr)
          ? arr.filter((x) => typeof x === "string" && x.trim()).slice(0, 9)
          : [];
        if (invites.length >= 1) return NextResponse.json({ invites });
      } catch {
        // 解析失败：交由前端用本地池兜底
      }
      return NextResponse.json({ error: "邀请生成失败。" }, { status: 500 });
    }

    return NextResponse.json({ text: stripMarkdownArtifacts(text) });
  } catch {
    return NextResponse.json({ error: "连接场域时出错，请稍后再试。" }, { status: 500 });
  }
}
