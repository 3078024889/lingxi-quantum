import {createHash} from 'node:crypto';
import {NextRequest,NextResponse} from 'next/server';
import {createAdminClient} from '@/lib/supabase/admin';
import {createClient} from '@/lib/supabase/server';
import {isSameOriginMutation} from '@/lib/sasi/request-security';
import {createBurnRevealToken} from '@/lib/tools/burn-link-token';
import {enforceAbuseGuard} from '@/lib/security/abuse-guard';
import {foodRequestIpHash} from '@/lib/tools/food/request-identity';
export const runtime='nodejs';
const TTL=new Set([10,60,1440,4320,10080]),VIEWS=new Set([1,3,5]),DUR=new Set([5,10,30,60]),MODES=new Set(['once','timed','limited','fast']);
export async function POST(req:NextRequest){
 if(!isSameOriginMutation(req))return NextResponse.json({error:'REQUEST_REJECTED'},{status:403});
 if(Number(req.headers.get('content-length')||0)>410000)return NextResponse.json({error:'INVALID_NOTE'},{status:413});
 const body=await req.json().catch(()=>null);if(!body)return NextResponse.json({error:'INVALID_BODY'},{status:400});
 const id=String(body.exportRequestId||'');
 if(!/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id))return NextResponse.json({error:'EXPORT_REQUEST_REQUIRED'},{status:400});
 const ciphertext=String(body.ciphertext||''),iv=String(body.iv||''),ttl=Number(body.ttlMinutes),mode=String(body.mode||'once'),views=Number(body.maxViews||1),duration=mode==='fast'?Number(body.viewDurationSeconds):null;
 if(ciphertext.length<10||ciphertext.length>400000||iv.length<8||iv.length>100||!TTL.has(ttl)||!MODES.has(mode)||!VIEWS.has(views)||(mode==='fast'&&!DUR.has(Number(duration))))return NextResponse.json({error:'INVALID_NOTE'},{status:400});
 const abuse=await enforceAbuseGuard(req,{scope:'burn-create',ipLimit:40,windowSeconds:3600});
 if(!abuse.ok)return NextResponse.json({error:abuse.error},{status:abuse.status});
 const {data:{user}}=await createClient().auth.getUser(),admin=createAdminClient();
 const fingerprint=createHash('sha256').update(JSON.stringify({ciphertext,iv,ttl,mode,views,duration})).digest('hex');
 const result=await admin.rpc('create_metered_burn_note',{p_id:id,p_user_id:user?.id||null,p_ip_hash:foodRequestIpHash(req),p_fingerprint:fingerprint,p_ciphertext:ciphertext,p_iv:iv,p_ttl_minutes:ttl,p_mode:mode,p_max_views:views,p_duration:duration});
 if(result.error)return NextResponse.json({error:'CREATE_FAILED'},{status:result.error.message?.includes('EXPORT_REQUEST_MISMATCH')?409:503});
 const note=result.data as {state:string;id?:string;expires_at?:string}|null;
 if(note?.state==='payment_required')return NextResponse.json({error:'EXPORT_PAYMENT_REQUIRED'},{status:402});
 if(note?.state==='gone')return NextResponse.json({error:'SHARE_GONE'},{status:410});
 if(note?.state!=='ready'||note.id!==id||!note.expires_at)return NextResponse.json({error:'CREATE_FAILED'},{status:503});
 return NextResponse.json({id:note.id,expiresAt:note.expires_at,token:createBurnRevealToken(note.id,note.expires_at)},{headers:{'Cache-Control':'no-store'}});
}
