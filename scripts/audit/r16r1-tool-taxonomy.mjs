import fs from"node:fs";
const seo=fs.readFileSync("lib/seo/global-seo.ts","utf8");
const taxonomy=fs.readFileSync("lib/tools/display-taxonomy.ts","utf8");
const hub=fs.readFileSync("components/tools/ToolsHubV11.tsx","utf8");
const copy=fs.readFileSync("lib/tools/hub-copy-v1470.ts","utf8");
const surface=fs.readFileSync("lib/tools/public-surface.ts","utf8");
const publicSlugs=[...seo.matchAll(/\{slug:"([^"]+)",zh:/g)].map(x=>x[1]);
if(publicSlugs.length!==118)throw new Error("R16R1_PUBLIC_TOOL_COUNT_DRIFT:"+publicSlugs.length);
if(new Set(publicSlugs).size!==publicSlugs.length)throw new Error("R16R1_DUPLICATE_PUBLIC_SLUG");
if(!surface.includes("GLOBAL_TOOL_CATALOG"))throw new Error("R16R1_PUBLIC_CATALOG_FALLBACK_MISSING");
if(hub.includes("DISPLAY_CATEGORY_BY_SLUG"))throw new Error("R16R1_LEGACY_CATEGORY_MAP_STILL_PRESENT");
