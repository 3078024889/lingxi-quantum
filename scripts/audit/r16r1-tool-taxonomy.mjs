if(!hub.includes("publicToolSurface()"))throw new Error("R16R1_SINGLE_SURFACE_MISSING");
for(const label of["文本 / 常用","文件 / 转换","其他"])if(!copy.includes(label))throw new Error("R16R1_HUMAN_LABEL_MISSING:"+label);
if(!taxonomy.includes('return"other"'))throw new Error("R16R1_OTHER_FALLBACK_MISSING");
