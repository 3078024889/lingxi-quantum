import fs from 'node:fs';
const must=(v,m)=>{if(!v)throw new Error(m)};
const profile=fs.readFileSync('miniapp/pages/profile/index.js','utf8');
const nav=fs.readFileSync('components/MobileBottomNav.tsx','utf8');
const app=JSON.parse(fs.readFileSync('miniapp/app.json','utf8'));
const profileDef=profile.search(/\bconst\s+PROFILE_UI\s*=/);
const pageCall=profile.search(/\bPage\s*\(\s*\{/);
must(profileDef>=0,'MINI_PROFILE_UI_MISSING');
must(pageCall>=0&&profileDef<pageCall,'MINI_PROFILE_UI_SCOPE_INVALID');
must(/PROFILE_UI\s*\[\s*['"]zh-CN['"]\s*\]/.test(profile),'MINI_PROFILE_UI_DEFAULT_NOT_WIRED');
must(/PROFILE_UI\s*\[\s*lang\s*\]/.test(profile),'MINI_PROFILE_UI_LANGUAGE_NOT_WIRED');
for(const k of ["'zh-CN'",'en:','ja:','ko:','fr:','de:','es:','pt:','ar:'])must(profile.includes(k),`MINI_PROFILE_UI_LOCALE_MISSING:${k}`);
must(!/label\s*:\s*c\.tasks/.test(nav),'MOBILE_PRIMARY_TASK_NAV_REMAINS');
must(!/href\s*:\s*['"]\/account\/orders['"]/.test(nav),'MOBILE_PRIMARY_TASK_ROUTE_REMAINS');
must(/href\s*:\s*['"]\/account['"][\s\S]{0,100}label\s*:\s*c\.account/.test(nav),'MOBILE_ACCOUNT_NAV_MISSING');
must(/href\s*:\s*['"]\/sasi['"][\s\S]{0,100}label\s*:\s*c\.create/.test(nav),'MOBILE_CREATE_NAV_MISSING');
const tabs=app.tabBar?.list?.map(x=>x.pagePath)||[];
must(JSON.stringify(tabs)===JSON.stringify(['pages/home/index','pages/tools/index','pages/create/index','pages/profile/index']),'MINI_NATIVE_TABBAR_DRIFT');
must(/openOrders\s*\(\s*\)\s*\{[\s\S]*?wx\.navigateTo\s*\(\s*\{\s*url\s*:\s*['"]\/pages\/orders\/index['"]/.test(profile),'MINI_ORDERS_SECONDARY_ENTRY_MISSING');
console.log('MINI_PROFILE_ACCOUNT_LOAD_CONTRACT=PASS');
console.log('MINI_PRIMARY_NAV_4=PASS');
console.log('MINI_ORDERS_SECONDARY_ENTRY=PASS');
console.log('MINI_V5_ACCOUNT_NAV_FIX_AUDIT=PASS');
