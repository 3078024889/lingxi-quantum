import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const storage = new Map();
const wx = {getStorageSync:k=>storage.get(k),setStorageSync:(k,v)=>storage.set(k,v),removeStorageSync:k=>storage.delete(k)};
const module = {exports:{}};
vm.runInNewContext(fs.readFileSync('miniapp/utils/topup-expiry.js','utf8'),{module,wx,Date});
const {expireCheckout,expiredOrder,TTL}=module.exports;
const now=Date.now();
storage.set('lx_mini_topup_pending',{orderId:'owned',createdAt:now-TTL+1});
assert.equal(expireCheckout(now),false);
assert.equal(expireCheckout(now+1),true);
assert.equal(storage.has('lx_mini_topup_pending'),false);
assert.equal(storage.get('lx_mini_expired_checkouts')[0].orderId,'owned');
const old={product_id:'sasi-balance-10',status:'pending',created_at:new Date(now-TTL).toISOString()};
assert.equal(expiredOrder(old,now),true);
assert.equal(expiredOrder({...old,status:'paid'},now),false,'Late confirmed payment must become visible again');
assert.equal(expiredOrder({...old,product_id:'toolquote:123'},now),false);
storage.set('lx_mini_topup_pending',{requestId:(now-TTL).toString(16).padEnd(32,'0')});
assert.equal(expireCheckout(now),true,'Legacy requests expire from their original request time');
storage.set('lx_mini_topup_pending',{requestId:'invalid'});
assert.equal(expireCheckout(now),false,'Unknown age is not proof of expiry');
console.log('PASS: five-minute boundary, legacy request recovery, paid records preserved and checkout release');
