const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const {createRequire}=require('node:module');
const share=require('../miniapp/utils/share');
for(const input of ['/account','/account/withdraw','/sasi/connections?token=private','/api/private','//evil.example','/tools\\evil'])assert.equal(share.publicWebPath(input),'/');
assert.equal(share.publicWebPath('/sasi?mode=image&threadId=private&projectId=private&token=secret'),'/sasi');
assert.equal(share.publicWebPath('/tools/resize-image?token=secret'),'/tools/resize-image');
assert.equal(share.publicWebPath('/sasi?mode=unknown&token=secret'),'/sasi');
const friend=share.appMessage('灵犀场','/pages/web/index?path=%2Fsiai');
const timeline=share.timeline('灵犀场','path=%2Fsiai');
assert.deepEqual(Object.keys(friend).sort(),['imageUrl','path','title']);
assert.deepEqual(Object.keys(timeline).sort(),['imageUrl','query','title']);
assert.equal(share.SHARE_IMAGE,'/assets/share-lingxifield-20261115.jpg');
assert.equal(friend.imageUrl,share.SHARE_IMAGE);
assert.equal(timeline.imageUrl,share.SHARE_IMAGE);
let definition,menu,navigation;
global.wx={showShareMenu:value=>{menu=value}};
const filename=path.resolve('miniapp/pages/share/index.js');
vm.runInNewContext(fs.readFileSync(filename,'utf8'),{require:createRequire(filename),Page:page=>{definition=page},wx:{showShareMenu:value=>{menu=value},navigateTo:value=>{navigation=value}},getCurrentPages:()=>[{}]},{filename});
const instance={...definition,data:{...definition.data},setData(value){Object.assign(this.data,value)}};
instance.onLoad({path:encodeURIComponent('/sasi?mode=image&threadId=secret'),title:encodeURIComponent('SASI智能软件市场')});
assert.deepEqual(Array.from(menu.menus),['shareAppMessage','shareTimeline']);
assert.equal(instance.data.webPath,'/sasi');
assert.equal(instance.onShareTimeline().query,'path='+encodeURIComponent('/sasi'));
assert.equal(instance.onShareAppMessage().path,'/pages/web/index?path='+encodeURIComponent('/sasi'));
instance.open();assert.equal(navigation.url,instance.onShareAppMessage().path);
const webJs=fs.readFileSync('miniapp/pages/web/index.js','utf8');
const webConfig=JSON.parse(fs.readFileSync('miniapp/pages/web/index.json','utf8'));
assert.doesNotMatch(webJs,/onShareTimeline/);
assert.match(webJs,/enableShareMenu\(\)/);
assert.equal(webConfig.enableShareAppMessage,true);
assert.equal(webConfig.enableShareTimeline,undefined);
const webWxml=fs.readFileSync('miniapp/pages/web/index.wxml','utf8');
assert.match(webWxml,/cover-view[\s\S]*bindtap="openNativeShare"/);
assert.match(webJs,/openNativeShare\(\).*pages\/share\/index/);
const page=fs.readFileSync('miniapp/pages/share/index.wxml','utf8');
assert.ok(!page.includes('<web-view'));
assert.ok(!page.includes('shareImage'));
assert.ok(JSON.parse(fs.readFileSync('miniapp/app.json','utf8')).pages.includes('pages/share/index'));
const mailHome=fs.readFileSync('miniapp/pages/mail-home/index.wxml','utf8')+fs.readFileSync('miniapp/pages/mail-home/index.js','utf8');
assert.doesNotMatch(mailHome,/mode=image|AI 图片|把想象变成图片|更多创作/);
assert.match(mailHome,/SASI 智能软件市场/);
console.log('PASS: native share page supports friends and timeline without a missing legacy cover; private routes are stripped; temp-mail links target current SASI marketplace.');
