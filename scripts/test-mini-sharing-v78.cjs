const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const {createRequire}=require('node:module');
const share=require('../miniapp/utils/share');
for(const input of ['/account','/account/withdraw','/sasi/connections?token=private','/api/private','//evil.example','/tools\\evil'])assert.equal(share.publicWebPath(input),'/');
assert.equal(share.publicWebPath('/sasi?mode=image&threadId=private&projectId=private&token=secret'),'/sasi?mode=image');
assert.equal(share.publicWebPath('/tools/resize-image?token=secret'),'/tools/resize-image');
assert.equal(share.publicWebPath('/sasi?mode=unknown&token=secret'),'/sasi');
let definition,menu,navigation;
global.wx={showShareMenu:value=>{menu=value}};
const filename=path.resolve('miniapp/pages/share/index.js');
vm.runInNewContext(fs.readFileSync(filename,'utf8'),{require:createRequire(filename),Page:page=>{definition=page},wx:{showShareMenu:value=>{menu=value},navigateTo:value=>{navigation=value}},getCurrentPages:()=>[{}]},{filename});
const instance={...definition,data:{...definition.data},setData(value){Object.assign(this.data,value)}};
instance.onLoad({path:encodeURIComponent('/sasi?mode=image&threadId=secret'),title:encodeURIComponent('AI图片生成')});
assert.deepEqual(Array.from(menu.menus),['shareAppMessage','shareTimeline']);
assert.equal(instance.data.webPath,'/sasi?mode=image');
assert.equal(instance.onShareTimeline().query,'path='+encodeURIComponent('/sasi?mode=image'));
assert.equal(instance.onShareAppMessage().path,'/pages/web/index?path='+encodeURIComponent('/sasi?mode=image'));
instance.open();assert.equal(navigation.url,instance.onShareAppMessage().path);
assert.ok(!fs.readFileSync('miniapp/pages/share/index.wxml','utf8').includes('<web-view'));
assert.ok(JSON.parse(fs.readFileSync('miniapp/app.json','utf8')).pages.includes('pages/share/index'));
console.log('PASS: real native share-page callbacks, friends/timeline public routes, private-route and credential stripping. WeChat client permission and formal-release acceptance require device verification.');
