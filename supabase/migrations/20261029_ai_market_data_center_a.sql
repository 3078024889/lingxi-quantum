create table if not exists public.ai_market_sources (
 id text primary key,
 source_name text not null,
 official_base_url text not null,
 license_note text,
 terms_url text,
 enabled boolean not null default false,
 rate_limit_per_minute integer not null default 10 check(rate_limit_per_minute between 1 and 600),
 last_success_at timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.ai_market_identity (
 id text primary key,
 entity_type text not null check(entity_type in ('company','product','model','version')),
 source_id text not null references public.ai_market_sources(id),
 upstream_id text not null,
 name text not null,
 source_url text not null,
 official_website text,
 status text not null default 'candidate' check(status in ('candidate','verified','rejected','discontinued')),
 metadata jsonb not null default '{}'::jsonb,
 first_seen_at timestamptz not null default now(),
 last_seen_at timestamptz not null default now(),
 verified_at timestamptz,
 verified_by uuid references auth.users(id),
 unique(entity_type,source_id,upstream_id),
 check ((status='verified')=(verified_at is not null and verified_by is not null))
);
create table if not exists public.ai_market_evidence (
 id bigint generated by default as identity primary key,
 entity_id text not null references public.ai_market_identity(id),
 source_id text not null references public.ai_market_sources(id),
 source_url text not null,
 collected_at timestamptz not null default now(),
 upstream_updated_at timestamptz,
 sha256 text check(sha256 is null or sha256 ~ '^[0-9a-f]{64}$'),
 evidence_type text not null check(evidence_type in ('identity','pricing','usage','license','funding','review','capability')),
 payload jsonb not null,
 checked boolean not null default false
);
create table if not exists public.ai_market_ingest_runs (
 id uuid primary key default gen_random_uuid(),
 source_id text not null references public.ai_market_sources(id),
 status text not null check(status in ('started','succeeded','failed')),
 started_at timestamptz not null default now(),
 completed_at timestamptz,
 fetched integer not null default 0,
 new_records integer not null default 0,
 failed_records integer not null default 0,
 error_message text
);
create index if not exists ai_market_identity_type_status on public.ai_market_identity(entity_type,status,name);
create index if not exists ai_market_identity_recent on public.ai_market_identity(last_seen_at desc,id);
create index if not exists ai_market_evidence_recent on public.ai_market_evidence(entity_id,collected_at desc);
create index if not exists ai_market_ingest_runs_recent on public.ai_market_ingest_runs(source_id,started_at desc);
