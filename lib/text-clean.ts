// ────────────────────────────────────────────────────────────────────
// AI 输出文本清理（兜底层）
// ────────────────────────────────────────────────────────────────────
// 系统提示词里已经明确要求AI"不要使用markdown语法"，但这只是对模型的
// 一句指令，不是强制约束——模型仍然有一定概率漏改（比如在强调某个词的
// 时候，习惯性地打上**加粗**），一旦漏改，星号会原样出现在给用户看的
// 报告里，非常影响可信度（"这看起来像是没写完的AI输出，不像正式报告"）。
//
// 这个函数不依赖模型自觉，在存库/展示之前，代码层面再过滤一遍——
// 双保险，而不是唯一的保险（真正的质量根源还是靠提示词和模型本身）。
export function stripMarkdownArtifacts(text: string): string {
  if (!text) return text;
  return (
    text
      // **加粗** / *斜体* → 去掉星号，保留文字本身
      .replace(/\*\*(.+?)\*\*/g, "$1")
      .replace(/(?<!\*)\*([^*\n]+?)\*(?!\*)/g, "$1")
      // 行首的 # 标题标记（比如模型偶尔把某节标题写成 "### 财富与事业"）
      .replace(/^#{1,6}\s+/gm, "")
      // 行首的 - / * 列表符号（报告是段落体，不需要markdown列表符号）
      .replace(/^[\-\*]\s+/gm, "")
      // 残留的孤立星号（比如没配对上的单个 * 或 **）
      .replace(/\*{1,2}/g, "")
      .trim()
  );
}
