import test from 'node:test';
import assert from 'node:assert/strict';
import {validateReviewFeedback} from './ai-market-review-validation.mjs';
const base=()=>({revision:'a'.repeat(40),category:'data',decision:'feedback',note:'The source is missing'});
test('valid feedback',()=>assert.equal(validateReviewFeedback(base())?.category,'data'));
test('invalid revision',()=>assert.equal(validateReviewFeedback({...base(),revision:'main'}),null));
test('invalid category',()=>assert.equal(validateReviewFeedback({...base(),category:'admin'}),null));
test('no publish decision',()=>assert.equal(validateReviewFeedback({...base(),decision:'approved'}),null));
test('reject too short',()=>assert.equal(validateReviewFeedback({...base(),note:'a'}),null));
test('reject oversize',()=>assert.equal(validateReviewFeedback({...base(),note:'x'.repeat(2001)}),null));
test('reject array input',()=>assert.equal(validateReviewFeedback([]),null));
