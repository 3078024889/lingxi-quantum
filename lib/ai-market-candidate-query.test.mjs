import test from 'node:test';
import assert from 'node:assert/strict';
import {parseCandidateQuery,escapePostgrestSearch} from './ai-market-candidate-query.mjs';
test('defaults to bounded first page',()=>assert.deepEqual(parseCandidateQuery({}),{status:'all',search:'',limit:25,page:1,offset:0}));
test('allows status filter and paging',()=>assert.equal(parseCandidateQuery({status:'candidate',page:'2',limit:'20'}).offset,20));
test('rejects huge pages',()=>assert.equal(parseCandidateQuery({page:'10001'}),null));
test('rejects huge limit',()=>assert.equal(parseCandidateQuery({limit:'1000'}),null));
test('rejects injection-like status',()=>assert.equal(parseCandidateQuery({status:'candidate,verified'}),null));
test('rejects long searches',()=>assert.equal(parseCandidateQuery({search:'a'.repeat(81)}),null));
test('sanitizes PostgREST special chars',()=>assert.equal(escapePostgrestSearch('abc,def(foo)%'), 'abc def foo'));
