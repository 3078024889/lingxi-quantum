assert.match(mini,/from\("lingxifield_announcements"\)/,"mini-program reads same live announcements");
assert.match(api,/\.eq\("is_active",true\)/);
assert.match(api,/\.in\("platform",\["all","web"\]\)/);
assert.match(api,/\.lte\("published_at",now\)/);
