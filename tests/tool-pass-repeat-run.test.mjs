import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const source=readFileSync("lib/tools/commerce/tool-repeat-meter.ts","utf8");
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
new Function("exports",compiled)(exports);
const check=exports.shouldClaimToolRun;
assert.equal(typeof check,"function");
assert.equal(check("file-1","","file-1"),false,"first process must use the just-claimed upload receipt");
assert.equal(check("file-1","file-1","file-1"),true,"second process must require a fresh claim");
assert.equal(check("file-2","","file-2"),false,"new upload receipt must not be charged twice");
assert.equal(check("file-1","file-1","file-2"),true,"changed batch with no matching upload receipt must claim");
assert.equal(check("","","file-1"),true,"workbench without upload receipt must claim");
assert.equal(check("file-1","file-1",""),false,"empty file batch cannot claim");
const workbench=readFileSync("components/tools/ToolWorkbench.tsx","utf8");
assert.match(workbench,/shouldClaimToolRun\(accessTicket\.current,processedFileSignature\.current,signature\)/);
assert.match(workbench,/processedFileSignature\.current=signature/);
assert.equal((workbench.match(/processedFileSignature\.current=""/g)||[]).length,2,"new upload and handoff both reset process state");
assert.match(workbench,/await claimToolStart\(tool\.slug,files\.length\)/);
console.log("TOOL_PASS_REPEAT_PROCESS_ON_SAME_FILE_TEST_PASS_NO_ECS_CHANGES");
