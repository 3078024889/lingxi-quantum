import {test,expect} from "./export-test";
import {PDFDocument,StandardFonts} from "pdf-lib";
import fs from "node:fs/promises";
import sharp from "sharp";

test("e-sign PDF: draw by hand, move and resize signature, add user stamp, export a real PDF and decode embedded images",async({page})=>{
 test.setTimeout(150000);
 const pdf=await PDFDocument.create();
 const font=await pdf.embedFont(StandardFonts.Helvetica);
 pdf.addPage([595,842]).drawText("Agreement for signature",{x:52,y:750,font,size:20});
 const source=Buffer.from(await pdf.save());
 const stamp=await sharp({create:{width:90,height:48,channels:4,background:"#cb3327"}}).png().toBuffer();
 const quoteId="11111111-1111-4111-8111-111111111111";
 let quoted=0,consumed=0,realPayment=0,quote:Record<string,unknown>;
 await page.addInitScript(()=>{window.open=()=>({} as Window)});
 await page.route("**/api/tools/quote",route=>{
  quoted++;const body=route.request().postDataJSON();
  expect(body.toolId).toBe("e-sign-pdf");expect(body.quantity).toBe(1);
  quote={id:quoteId,tool_id:"e-sign-pdf",quantity:1,unit_name:"page",currency:body.currency,display_currency:body.currency,display_amount:1,amount_usd:1,amount_rmb:1,expires_at:new Date(Date.now()+3600000).toISOString(),metadata:body.metadata};
  return route.fulfill({json:quote});
 });
 await page.route("**/api/tools/pay/status**",route=>route.fulfill({json:{paid:true,quote,grant:{}}}));
 await page.route("**/api/tools/export/consume",route=>{consumed++;return route.fulfill({json:{ok:true}})});
 await page.route("**/api/tools/pay/create",route=>{realPayment++;return route.fulfill({status:500,json:{error:"REAL_PAYMENT_FORBIDDEN"}})});
 await page.goto("/tools/e-sign-pdf?lang=en");
 await page.locator('input[type="file"]').first().setInputFiles({name:"sign-me.pdf",mimeType:"application/pdf",buffer:source});
 await expect(page.getByTestId("pdf-source-preview")).toBeVisible({timeout:30000});
 await page.getByRole("button",{name:"Draw signature",exact:true}).click();
 const pad=page.getByTestId("signature-draw-pad");
 await expect(pad).toBeVisible();
 const rect=await pad.getByRole("img",{name:"Draw your signature"}).boundingBox();
 expect(rect).not.toBeNull();
 const x=rect!.x+rect!.width*.18,y=rect!.y+rect!.height*.48;
 await page.mouse.move(x,y);await page.mouse.down();
 await page.mouse.move(x+rect!.width*.4,y-12,{steps:12});
 await page.mouse.move(x+rect!.width*.53,y+16,{steps:9});await page.mouse.up();
 await pad.getByRole("button",{name:"Place in PDF",exact:true}).click();
 const overlays=page.locator('[data-testid="pdf-overlay"][data-overlay-kind="image"]');
 await expect(overlays).toHaveCount(1);
 const first=overlays.first(),before=await first.boundingBox();expect(before).not.toBeNull();
 await first.scrollIntoViewIfNeeded();
 const handle=page.getByRole("button",{name:"Resize se",exact:true});
 await expect(handle).toBeVisible();
 const h=await handle.boundingBox();expect(h).not.toBeNull();
 await page.mouse.move(h!.x+h!.width/2,h!.y+h!.height/2);await page.mouse.down();
 await page.mouse.move(h!.x+h!.width/2+30,h!.y+h!.height/2+15,{steps:5});await page.mouse.up();
 const after=await first.boundingBox();
 expect(after!.width).toBeGreaterThan(before!.width+7);
 await page.locator("label").filter({hasText:"Add stamp"}).locator('input[type="file"]').setInputFiles({name:"owned-stamp.png",mimeType:"image/png",buffer:stamp});
 await expect(overlays).toHaveCount(2);
 await page.getByRole("button",{name:"Preview",exact:true}).click();
 await expect(page.getByTestId("pdf-export-preview").first()).toBeVisible({timeout:30000});
 const pending=page.waitForEvent("download",{timeout:100000});
 await page.getByTestId("paid-export-start").click();
 await expect.poll(()=>quoted).toBe(1);
 await page.evaluate(()=>window.dispatchEvent(new Event("pageshow")));
 const dl=await pending;expect(await dl.failure()).toBeNull();
 const bytes=await fs.readFile((await dl.path())!);
 expect(bytes.subarray(0,5).toString()).toBe("%PDF-");
 const reopened=await PDFDocument.load(bytes);
 expect(reopened.getPageCount()).toBe(1);
 const pdfjs=await import("pdfjs-dist/legacy/build/pdf.mjs");
 const loaded=await pdfjs.getDocument({data:new Uint8Array(bytes)}).promise;
 const operators=await (await loaded.getPage(1)).getOperatorList();
 const paint=operators.fnArray.filter(n=>n===pdfjs.OPS.paintImageXObject||n===pdfjs.OPS.paintInlineImageXObject);
 expect(paint.length).toBeGreaterThanOrEqual(2);
 await loaded.destroy();
 expect(quoted).toBe(1);expect(consumed).toBe(1);expect(realPayment).toBe(0);
});
