 test("PDF original vector text is clickable, editable, masked, and present in exported preview",async({page})=>{
  const {PDFDocument,StandardFonts}=await import("pdf-lib");
  const doc=await PDFDocument.create(),sheet=doc.addPage([595,842]);
  const font=await doc.embedFont(StandardFonts.Helvetica);
  sheet.drawText("Original PDF headline",{x:72,y:720,size:20,font});
  const png=Buffer.from("iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAYAAAAf8/9hAAAAHUlEQVR4nGM8ISe3hYECwESJ5lEDRg0YNWAwGQAAPMsB2FuN7EwAAAAASUVORK5CYII=","base64");
  const embedded=await doc.embedPng(png);
  sheet.drawImage(embedded,{x:300,y:540,width:100,height:80});
  const pdf=Buffer.from(await doc.save());
  await page.goto("/tools/pdf-editor?lang=en");
  await page.locator('input[type="file"]').first().setInputFiles({name:"original-text.pdf",mimeType:"application/pdf",buffer:pdf});
  await expect(page.getByTestId("pdf-source-preview")).toBeVisible({timeout:30000});
  const original=page.getByRole("button",{name:"Edit existing text: Original PDF headline"});
  await expect(original).toBeVisible({timeout:20000});
  if(await page.evaluate(()=>window.matchMedia("(pointer:coarse)").matches))await original.click();else await original.dblclick();
  const editor=page.getByRole("textbox",{name:"Edit PDF text"});
  await expect(editor).toBeVisible();
  await editor.fill("Revised PDF headline");
  await editor.press("Enter");
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(1);
  const embeddedImage=page.getByTestId("pdf-original-image");
  await expect(embeddedImage).toHaveCount(1,{timeout:20000});
  const hideImage=page.getByTestId("pdf-original-image-hide");
  await expect(hideImage).toBeVisible();
  await hideImage.click();
  await expect(page.getByTestId("pdf-original-image")).toHaveCount(0);
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(2);
  await page.getByRole("button",{name:/Undo/}).click();
  await expect(embeddedImage).toHaveCount(1);
  if(await page.evaluate(()=>window.matchMedia("(pointer:coarse)").matches))await embeddedImage.click();else await embeddedImage.dblclick();
  await page.locator('input[type="file"][accept="image/png,image/jpeg,image/webp"]').setInputFiles({name:"replacement.png",mimeType:"image/png",buffer:png});
  await expect(page.getByTestId("pdf-original-image")).toHaveCount(0);
  await expect(page.locator('[data-testid="pdf-overlay"][data-overlay-kind="image"]')).toHaveCount(1);
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(2);
  const replaced=page.locator('[data-testid="pdf-overlay"][data-overlay-kind="text"]');
  await expect(replaced).toContainText("Revised PDF headline");
  await expect(page.getByText(/Original text may remain in PDF data/)).toBeVisible();
  await page.getByRole("button",{name:"Preview",exact:true}).click();
  await expect(page.getByTestId("pdf-export-preview").first()).toBeVisible({timeout:30000});
  await page.getByRole("button",{name:/Undo/}).click();
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(1);
  await expect(page.getByTestId("pdf-original-image")).toHaveCount(1);
  await page.getByRole("button",{name:/Undo/}).click();
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(1);
  await page.getByRole("button",{name:/Undo/}).click();
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(0);
  await expect(original).toBeVisible();
  await page.getByRole("button",{name:/Redo/}).click();
  await page.getByRole("button",{name:/Redo/}).click();
  await page.getByRole("button",{name:/Redo/}).click();
  await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(2);
 });
