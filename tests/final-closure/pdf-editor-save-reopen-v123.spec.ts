import {test,expect} from "./export-test";
import {PDFDocument,StandardFonts,rgb} from "pdf-lib";
import fs from "node:fs/promises";
import sharp from "sharp";

test("PDF editor: edit existing vector headline, insert movable image, complete isolated paid export, download and reopen",async({page})=>{
 test.setTimeout(120000);
 const source=await PDFDocument.create();
 const sheet=source.addPage([595,842]);const font=await source.embedFont(StandardFonts.Helvetica);
 sheet.drawText("Original Agreement",{x:75,y:708,size:20,font,color:rgb(.1,.1,.1)});
 const original=Buffer.from(await source.save());
 const replacement=await sharp({create:{width:62,height:23,channels:3,background:"#e32957"}}).png().toBuffer();
 const quoteId="11111111-1111-4111-8111-111111111111";
 let quote:any,quoted=0,consume=0,realPayment=0;
 await page.addInitScript(()=>{window.open=()=>({} as Window)});
 await page.route("**/api/tools/quote",route=>{
  quoted++;const body=route.request().postDataJSON();
  expect(body.toolId).toBe("pdf-editor");
  expect(body.quantity).toBe(1);
  quote={id:quoteId,tool_id:"pdf-editor",quantity:1,unit_name:"page",currency:body.currency,display_currency:body.currency,display_amount:1,amount_usd:1,amount_rmb:1,expires_at:new Date(Date.now()+3600000).toISOString(),metadata:body.metadata};
  return route.fulfill({json:quote});
 });
 await page.route("**/api/tools/pay/status**",route=>route.fulfill({json:{paid:true,quote,grant:{}}}));
 await page.route("**/api/tools/export/consume",route=>{consume++;return route.fulfill({json:{ok:true}})});
 await page.route("**/api/tools/pay/create",route=>{realPayment++;return route.fulfill({status:500,json:{error:"REAL_PAYMENT_FORBIDDEN"}})});
 await page.goto("/tools/pdf-editor?lang=en");
 await page.locator('input[type="file"]').first().setInputFiles({name:"agreement.pdf",mimeType:"application/pdf",buffer:original});
 const headline=page.getByRole("button",{name:"Edit existing text: Original Agreement"});
 await expect(headline).toBeVisible({timeout:30000});
 if(await page.evaluate(()=>matchMedia("(pointer:coarse)").matches))await headline.click();else await headline.dblclick();
 const editor=page.getByRole("textbox",{name:"Edit PDF text"});
 await expect(editor).toBeVisible();
 await editor.fill("Updated Agreement");
 await editor.press("Enter");
 await expect(page.getByTestId("pdf-original-text-mask")).toHaveCount(1);
 await page.locator('input[type="file"][accept="image/*"]').first().setInputFiles({name:"logo.png",mimeType:"image/png",buffer:replacement});
 const image=page.locator('[data-testid="pdf-overlay"][data-overlay-kind="image"]').last();
 await expect(image).toBeVisible();
 const dimensions=await image.boundingBox();expect(dimensions!.width).toBeGreaterThan(40);
 await image.click();
 await page.getByRole("button",{name:"Preview",exact:true}).click();
 await expect(page.getByTestId("pdf-export-preview").first()).toBeVisible({timeout:30000});
 const waiting=page.waitForEvent("download",{timeout:90000});
 await page.getByTestId("paid-export-start").click();
 await expect.poll(()=>quoted,{timeout:30000}).toBe(1);
 await page.evaluate(()=>window.dispatchEvent(new Event("pageshow")));
 const exported=await waiting;
 expect(exported.suggestedFilename()).toContain("agreement.pdf");
 expect(await exported.failure()).toBeNull();
 const bytes=await fs.readFile((await exported.path())!);
 expect(bytes.slice(0,5).toString("ascii")).toBe("%PDF-");
 const reopened=await PDFDocument.load(bytes);
 expect(reopened.getPageCount()).toBe(1);
 expect(reopened.getPage(0).getWidth()).toBe(595);
 const pdfjs=await import("pdfjs-dist/legacy/build/pdf.mjs");
 const opened=await pdfjs.getDocument({data:new Uint8Array(bytes)}).promise;
 const text=(await (await opened.getPage(1)).getTextContent()).items.map((v:any)=>v.str||"").join(" ");
 expect(text).toContain("Original Agreement");
 const operators=await (await opened.getPage(1)).getOperatorList();
 expect(operators.fnArray.filter(op=>op===pdfjs.OPS.paintImageXObject||op===pdfjs.OPS.paintInlineImageXObject).length).toBeGreaterThan(0);
 await opened.destroy();
 expect(quoted).toBe(1);expect(consume).toBe(1);expect(realPayment).toBe(0);
});
